function [grade,x] = calculate_grade()
%weights
weights = struct( ...
    'projects',30/100, ...
    'exam1',15/100, ...
    'exam2',15/100, ...
    'final',20/100, ...
    'quizzes',20/100);
%grades
scores = struct( ...
    'projects',[71.11 73.33 100 85 96.67 77.83 100 100], ...
    'exam1',20.33/25, ...
    'exam2',20/25, ...
    'final',80, ...
    'quizzes',[73.33 40 50 20 0 0 46.67 46.67 40 86.67]);
%letter
letter_grades = { ...
    90 'A'; ...
    80 'B'; ...
    70 'C'; ...
    60 'D'; ...
    -Inf 'F'};

    types = fieldnames(weights);
x = 0;
for i = 1:numel(types)
    x = x+weights.(types{i})*mean(scores.(types{i}));
end
idx = find([letter_grades{:,1}] <= x,1);
grade = letter_grades{idx,2};